CREATE TABLE documents (
 id VARCHAR(40) NOT NULL, version VARCHAR(100) NOT NULL, body MEDIUMTEXT NOT NULL,
 sha256 CHAR(64) NOT NULL, href VARCHAR(500) NOT NULL, active TINYINT NOT NULL DEFAULT 0,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(id, version)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE applications (
 id CHAR(32) PRIMARY KEY, request_key CHAR(64) NOT NULL UNIQUE, request_hash CHAR(64) NOT NULL,
 kind VARCHAR(20) NOT NULL, data MEDIUMTEXT NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE inventory (
 id INT PRIMARY KEY, capacity INT NOT NULL, held INT NOT NULL DEFAULT 0
) ENGINE=InnoDB;
INSERT INTO inventory(id,capacity,held) VALUES(1,100,0);
CREATE TABLE orders (
 id CHAR(32) PRIMARY KEY, request_key CHAR(64) NOT NULL UNIQUE, request_hash CHAR(64) NOT NULL,
 buyer TEXT NOT NULL, status VARCHAR(24) NOT NULL DEFAULT 'reserved', amount INT NOT NULL,
 currency CHAR(3) NOT NULL DEFAULT 'RUB', access_hash CHAR(64) NOT NULL UNIQUE,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(status,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE consents (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 application_id CHAR(32) NULL, order_id CHAR(32) NULL,
 kind VARCHAR(24) NOT NULL, contact TEXT NOT NULL, ip VARCHAR(45) NOT NULL,
 marks TEXT NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(application_id) REFERENCES applications(id), FOREIGN KEY(order_id) REFERENCES orders(id),
 INDEX(created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE consent_documents (
 consent_id BIGINT UNSIGNED NOT NULL, document_id VARCHAR(40) NOT NULL, version VARCHAR(100) NOT NULL,
 PRIMARY KEY(consent_id,document_id), FOREIGN KEY(consent_id) REFERENCES consents(id) ON DELETE CASCADE,
 FOREIGN KEY(document_id,version) REFERENCES documents(id,version)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE payments (
 order_id CHAR(32) PRIMARY KEY, provider_id VARCHAR(64) NULL UNIQUE,
 idempotence_key CHAR(32) NOT NULL UNIQUE, request_body MEDIUMTEXT NOT NULL,
 status VARCHAR(32) NOT NULL DEFAULT 'creating', confirmation_url TEXT NULL,
 receipt_status VARCHAR(32) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, checked_at DATETIME NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id), INDEX(status,checked_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE tickets (
 id CHAR(32) PRIMARY KEY, order_id CHAR(32) NOT NULL UNIQUE, number VARCHAR(32) NOT NULL UNIQUE,
 token_hash CHAR(64) NOT NULL UNIQUE, token_cipher TEXT NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'valid', created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES orders(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE mail_queue (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, dedupe VARCHAR(128) NOT NULL UNIQUE,
 kind VARCHAR(32) NOT NULL, reference_id CHAR(32) NULL, recipient TEXT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending', attempts INT NOT NULL DEFAULT 0,
 available_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, locked_at DATETIME NULL,
 lock_token CHAR(32) NULL, last_error VARCHAR(64) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, sent_at DATETIME NULL,
 INDEX(status,available_at), INDEX(kind,reference_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE staff (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role VARCHAR(20) NOT NULL, active TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE admissions (
 ticket_id CHAR(32) PRIMARY KEY, staff_id INT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(ticket_id) REFERENCES tickets(id), FOREIGN KEY(staff_id) REFERENCES staff(id)
) ENGINE=InnoDB;
CREATE TABLE refunds (
 id CHAR(32) PRIMARY KEY, order_id CHAR(32) NOT NULL, staff_id INT UNSIGNED NULL,
 request_key CHAR(64) NOT NULL UNIQUE, provider_id VARCHAR(64) NULL UNIQUE,
 amount INT NOT NULL, status VARCHAR(32) NOT NULL DEFAULT 'creating',
 request_body MEDIUMTEXT NOT NULL, receipt_status VARCHAR(32) NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, checked_at DATETIME NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id), FOREIGN KEY(staff_id) REFERENCES staff(id), INDEX(order_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE rate_limits (
 bucket CHAR(64) PRIMARY KEY, hits INT NOT NULL, expires_at DATETIME NOT NULL, INDEX(expires_at)
) ENGINE=InnoDB;
CREATE TABLE staff_audit (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, staff_id INT UNSIGNED NOT NULL,
 action VARCHAR(40) NOT NULL, reference_id VARCHAR(64) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(staff_id) REFERENCES staff(id)
) ENGINE=InnoDB;
